#!/bin/bash
# Build the XP install package (HermesXP.zip): everything a user needs to
# get Messenger working on an XP machine, in one file.
#
# Contents (all generated from the live local server, nothing hardcoded):
#   HermesXP.exe            the companion exe (probe + installer mode)
#   hermesxp.ini            connection config: server IP + owner address
#   ca.pem                  the local CA (the exe installs it into Trusted Root)
#   escargot.dll            Escargot's Switcher (downloaded at package time,
#                           cached under ~/.hermes/msn-server/switcher-dl/)
#   msnmsgr.exe-escargot.ini / wlcomm.exe-escargot.ini
#                           Switcher settings, filled with the server IP
#   README.txt              install steps (incl. the one manual PE-edit step)
#
# Output: ~/.hermes/msn-server/xp-package/HermesXP.zip
# Get it from the LAN at http://<ZBook LAN IP>:18767/HermesXP.zip (the
# hermes-xp-package service), or copy the zip to a USB drive.
#
# Usage: ./build-xp-package.sh [repo-root]   (default: the repo this script lives in)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="${1:-$(cd "$SCRIPT_DIR/.." && pwd)}"
HERMES_HOME="${HERMES_HOME:-$HOME/.hermes}"
SERVER_DIR="$HERMES_HOME/msn-server"
PKG_DIR="$SERVER_DIR/xp-package"
STAGE="$PKG_DIR/files"
SWITCHER_URL="https://storage.levelleap.com/nina/clients/msnp/escargot-switcher.zip"
SWITCHER_DL="$SERVER_DIR/switcher-dl"

log() { echo "[xp-package] $*"; }
warn() { echo "[xp-package] WARNING: $*" >&2; }

# Remove previously published secrets before any operation that can fail.
rm -f -- "$PKG_DIR/HermesXP.zip"
rm -f -- "$PKG_DIR/HermesXP-Setup.exe"
rm -rf -- "$STAGE"

# Server IP: override with LAN_IP env; otherwise auto-detect.
if [ -z "${LAN_IP:-}" ]; then
    LAN_IP="$(ip route get 1.1.1.1 2>/dev/null | sed -n 's/.*src \([0-9.]*\).*/\1/p')"
    [ -z "$LAN_IP" ] && LAN_IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
fi
[ -n "$LAN_IP" ] || { echo "[xp-package] could not detect LAN IP; set LAN_IP env" >&2; exit 1; }

# Owner address is non-secret. Never put any passwords in the LAN package.
OWNER_EMAIL="user@hermes.local"
if [ -f "$HERMES_HOME/.env" ]; then
    OWNER_EMAIL="$(grep -E '^HERMES_MSN_OWNER_EMAIL=' "$HERMES_HOME/.env" | cut -d= -f2- | head -1 || true)"
    [ -z "$OWNER_EMAIL" ] && OWNER_EMAIL="user@hermes.local"
fi
log "server $LAN_IP, owner $OWNER_EMAIL"

# 1. Build the exe from source (deterministic build; same source = same bytes).
bash "$SCRIPT_DIR/build-exe.sh" "$REPO_ROOT" || { echo "[xp-package] exe build failed" >&2; exit 1; }

# Remove legacy staging data, which may include a previously published password.
rm -rf -- "$STAGE"
mkdir -p "$STAGE" "$SWITCHER_DL"
cp "$REPO_ROOT/dist/HermesXP.exe" "$STAGE/HermesXP.exe"

# 2. Public connection config. Enter the password privately in Messenger.
cat > "$STAGE/hermesxp.ini" <<EOF
[Hermes]
ServerIP=$LAN_IP
OwnerEmail=$OWNER_EMAIL
ProbePort=18765
EOF

# 3. Local CA (the exe installs it into Trusted Root).
if [ -f "$SERVER_DIR/certs/ca.pem" ]; then
    cp "$SERVER_DIR/certs/ca.pem" "$STAGE/ca.pem"
else
    warn "no CA yet ($SERVER_DIR/certs/ca.pem missing) — run install.sh first"
fi

# 4. Switcher INIs (generated by install.sh with this host's LAN IP).
for exe in msnmsgr wlcomm; do
    if [ -f "$SERVER_DIR/switcher/$exe.exe-escargot.ini" ]; then
        cp "$SERVER_DIR/switcher/$exe.exe-escargot.ini" "$STAGE/$exe.exe-escargot.ini"
    else
        warn "switcher INI for $exe missing — run install.sh first"
    fi
done

# 5. Switcher DLL (downloaded at package time, cached; never vendored).
DLL="$SWITCHER_DL/escargot.dll"
if [ ! -f "$DLL" ]; then
    log "downloading Escargot Switcher..."
    if curl -fsSL -o "$SWITCHER_DL/escargot-switcher.zip" "$SWITCHER_URL" 2>/dev/null; then
        python3 - "$SWITCHER_DL/escargot-switcher.zip" "$SWITCHER_DL" <<'PYEOF'
import sys, zipfile
z = zipfile.ZipFile(sys.argv[1])
for name in z.namelist():
    if name.lower().endswith("escargot.dll"):
        z.extract(name, sys.argv[2])
        import os
        src = os.path.join(sys.argv[2], name)
        os.rename(src, os.path.join(sys.argv[2], "escargot.dll"))
        print("extracted", name)
        break
else:
    print("escargot.dll not found in the zip", file=sys.stderr)
    sys.exit(1)
PYEOF
    else
        warn "Switcher download failed — packaging without escargot.dll (see README for the link)"
    fi
fi
if [ -f "$DLL" ]; then
    cp "$DLL" "$STAGE/escargot.dll"
    log "escargot.dll: $(stat -c%s "$DLL") bytes"
fi

# 6. README.
sed -e "s/__LAN_IP__/$LAN_IP/g" -e "s/__OWNER_EMAIL__/$OWNER_EMAIL/g" \
    "$SCRIPT_DIR/xp-package-readme.txt.template" > "$STAGE/README.txt"

# 7. Zip it (python zipfile: always available here).
python3 - "$STAGE" "$PKG_DIR/HermesXP.zip" <<'PYEOF'
import sys, os, zipfile
stage, out = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    for name in sorted(os.listdir(stage)):
        z.write(os.path.join(stage, name), name)
print("wrote", out)
PYEOF

SIZE="$(stat -c%s "$PKG_DIR/HermesXP.zip")"
log "package ready: $PKG_DIR/HermesXP.zip ($SIZE bytes)"
log "download: http://$LAN_IP:18767/HermesXP.zip (or copy it to a USB drive)"

# Prefer a normal Windows XP installer with Add/Remove Programs integration.
# The ZIP remains available for legacy/manual transfers.
if command -v makensis >/dev/null 2>&1 && [ -f "$REPO_ROOT/xp-client/HermesXP-Setup.nsi" ]; then
    bash "$SCRIPT_DIR/build-xp-installer.sh" "$REPO_ROOT"
    log "installer: http://$LAN_IP:18767/HermesXP-Setup.exe"
else
    warn "NSIS not installed; portable ZIP generated but Setup.exe unavailable"
fi
